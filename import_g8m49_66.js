let updated = 0, added = 0, skipped = 0;

imageGroups.forEach(([imgName, cardList]) => {
  cardList.forEach((row, pos) => {
    const [id, name, type, prereq, cost, pass, vp, bonus, deck, desc] = row;

    if (!id) {
      console.log(`SKIP (no ID): ${name} in ${imgName}`);
      skipped++;
      return;
    }

    const vpVal = toVP(vp);
    const bonusVal = toBonus(bonus);
    const gridCol = pos % 3;
    const gridRow = Math.floor(pos / 3);

    const existing = cards.find(c => c['卡片ID'] === id);
    if (existing) {
      existing['牌名'] = toStr(name);
      existing['類型'] = toStr(type);
      existing['先決條件'] = toStr(prereq);
      existing['費用'] = toStr(cost);
      existing['是否傳遞'] = toStr(pass);
      existing['勝利點數'] = vpVal;
      existing['紅利分數'] = bonusVal;
      existing['牌組'] = toStr(deck);
      existing['說明'] = toStr(desc);
      existing['source_image'] = imgName;
      existing['position'] = pos;
      existing['grid_col'] = gridCol;
      existing['grid_row'] = gridRow;
      updated++;
      console.log(`updated: ${name} (${id}) → ${imgName}[${pos}]`);
    } else {
      cards.push({
        牌名: toStr(name),
        類型: toStr(type),
        先決條件: toStr(prereq),
        費用: toStr(cost),
        是否傳遞: toStr(pass),
        勝利點數: vpVal,
        紅利分數: bonusVal,
        牌組: toStr(deck),
        卡片ID: id,
        說明: toStr(desc),
        card_type: 'minor',
        source_image: imgName,
        position: pos,
        grid_col: gridCol,
        grid_row: gridRow,
      });
      added++;
      console.log(`added: ${name} (${id}) → ${imgName}[${pos}]`);
    }
  });
});

fs.writeFileSync('./cards.json', JSON.stringify(cards, null, 2), 'utf8');
console.log(`\nDone: ${updated} updated, ${added} added, ${skipped} skipped. Total: ${cards.length}`);
