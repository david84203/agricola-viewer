let cards = JSON.parse(fs.readFileSync('cards.json', 'utf8'));

const lines = userText.trim().split('\n');
lines.forEach(line => {
  const parts = line.split('\t').map(s => s.trim());
  if (parts.length >= 10) {
    let id = parts[0];
    // Fix IDs that were typos in the user's paste (likely from earlier OCR)
    if (id === 'I092分' || parts[1] === '擠奶棚') id = 'I093';
    if (id === 'I無02' || parts[1] === '野生動物保留區') id = 'I102';

    const cardIndex = cards.findIndex(c => c.卡片ID === id || (c.牌名 === parts[1] && c.牌組 === 'I' && c.card_type === 'minor'));
    if (cardIndex !== -1) {
      cards[cardIndex].卡片ID = id;
      cards[cardIndex].牌名 = parts[1];
      cards[cardIndex].先決條件 = parts[3];
      cards[cardIndex].費用 = parts[4];
      cards[cardIndex].是否傳遞 = parts[5];
      cards[cardIndex].勝利點數 = parts[6];
      cards[cardIndex].紅利分數 = parts[7];
      cards[cardIndex].牌組 = 'I';
      cards[cardIndex].說明 = parts[9];
    } else {
      console.log('Not found:', id, parts[1]);
    }
  }
});

fs.writeFileSync('cards.json', JSON.stringify(cards, null, 2));
console.log('Successfully updated I Minor cards with user data.');
